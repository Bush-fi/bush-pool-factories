// Writes contracts/Imports.sol, which imports every contract shipped by the @bush.fi/v3-* packages so that
// `hardhat compile` produces artifacts and typechain types for all of them. Re-run after bumping a package.
const fs = require('fs');
const path = require('path');

const PACKAGES = [
  'v3-interfaces',
  'v3-solidity-utils',
  'v3-vault',
  'v3-pool-utils',
  'v3-pool-weighted',
  'v3-pool-stable',
  'v3-pool-hooks',
  'v3-pool-cow',
];

// Vault tests interact with Permit2 through its interface only; the deployed bytecode is embedded in Permit2Deployer.
const EXTRA = ['permit2/src/interfaces/IPermit2.sol'];

function solFiles(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const full = path.join(dir, entry.name);
    return entry.isDirectory() ? solFiles(full) : entry.name.endsWith('.sol') ? [full] : [];
  });
}

const imports = [];
for (const pkg of PACKAGES) {
  const root = path.dirname(require.resolve(`@bush.fi/${pkg}/package.json`));
  const contracts = path.join(root, 'contracts');
  for (const file of solFiles(contracts).sort()) {
    imports.push(`@bush.fi/${pkg}/${path.relative(root, file)}`);
  }
}
imports.push(...EXTRA);

const out = [
  '// SPDX-License-Identifier: GPL-3.0-or-later',
  '// GENERATED by scripts/generate-imports.js - do not edit by hand.',
  '',
  'pragma solidity ^0.8.24;',
  '',
  // Namespaced so that same-named symbols from different packages don't clash in this file's scope.
  ...imports.map((file, i) => `import "${file}" as I${i};`),
  '',
].join('\n');

const target = path.join(__dirname, '..', 'contracts', 'Imports.sol');
fs.writeFileSync(target, out);
console.log(`Wrote ${imports.length} imports to ${path.relative(process.cwd(), target)}`);
